/// Parse `raw` (generic netlink header followed by attributes) and check
/// that emitting the parsed message reproduces `raw` byte for byte.
fn assert_parse_and_emit(raw: &[u8], expected: &MacsecMessage) {
    let header = GenlHeader::parse(raw).unwrap();
    assert_eq!(
        &MacsecMessage::parse_with_param(&raw[4..], header).unwrap(),
        expected
    );

    let mut buffer = Vec::new();
    header.emit(&mut buffer).unwrap();
    expected.emit(&mut buffer).unwrap();
    assert_eq!(&buffer, &raw);
}

