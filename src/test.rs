#[test]
fn test_attribute_conversions() {
    assert_eq!(
        MacSecCipherId::from(0x0080C20001000004),
        MacSecCipherId::GcmAesXpn256
    );
    assert_eq!(u64::from(MacSecCipherId::GcmAes256), 0x0080C20001000002);
    assert_eq!(MacSecValidate::from(2), MacSecValidate::Strict);
    assert_eq!(u8::from(MacSecValidate::Check), 1);
    assert_eq!(MacSecOffload::from(1), MacSecOffload::Phy);
    assert_eq!(u8::from(MacSecOffload::Off), 0);
}

